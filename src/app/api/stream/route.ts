/**
 * API Route Handler: Streaming Text Completion
 * Endpoint: POST /api/stream
 * 
 * Concepts Demonstrated:
 * 1. `streamText` Function (Vercel AI SDK Core):
 *    - Initiates an asynchronous streaming request to the model provider.
 *    - Instead of waiting for the full response, chunks/tokens are streamed
 *      to the client as they are generated, drastically reducing Time to First Token (TTFT).
 * 2. Streaming Response Protocol:
 *    - `result.toUIMessageStreamResponse()`: Converts the streaming output into a
 *      standardized HTTP streaming response (SSE / chunked data stream) compatible
 *      with client hooks like `useCompletion` from `@ai-sdk/react`.
 * 3. Asynchronous Usage & Telemetry:
 *    - `result.usage`: A Promise that resolves once all tokens have finished streaming.
 *    - Essential for calculating OpenAI billing costs, monitoring prompt vs completion
 *      token ratios, and diagnosing token bloat.
 * 4. Rate Limiting Protection (`withRateLimit`):
 *    - Enforces IP-based fixed window quotas before allocating OpenAI streaming tokens.
 */

import { streamText } from "ai";
import { textModel } from "../../../lib/ai-model";
import { withRateLimit } from "../../../lib/rate-limit";

/**
 * Core handler logic for streaming completions.
 */
async function handlePost(request: Request) {
  try {
    // 1. Parse the incoming request containing the prompt string
    const { prompt } = await request.json();

    // 2. Start the streaming completion
    const result = streamText({
      model: textModel,
      prompt,
    });

    console.log("Streaming text response initiated.", result);

    // 3. Track token usage asynchronously (resolves when stream finishes)
    result.usage.then((usage) => {
      console.log("Token usage:", usage);
      console.log({
        inputTokens: usage.inputTokens,   // Tokens used by user prompt
        outputTokens: usage.outputTokens, // Tokens generated by AI
        totalTokens: usage.totalTokens,   // Total tokens billed for this call
      });
    });

    // 4. Return an HTTP streaming response to the client
    return result.toUIMessageStreamResponse();
  } catch (error) {
    console.error("Error streaming text:", error);
    return Response.json(
      { error: "Failed to stream text" },
      { status: 500 }
    );
  }
}

/**
 * Next.js Route Handler for HTTP POST requests.
 * Enforces per-IP rate limits before streaming.
 */
export function POST(request: Request) {
  return withRateLimit(request, "stream", () => handlePost(request));
}
